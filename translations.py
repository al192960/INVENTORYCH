def translate(key, language='es', **kwargs):
    """Devuelve la traducción y reemplaza parámetros dinámicos seguros."""
    if language not in ('es', 'en'):
        language = 'es'
    values = TEXTS.get(key)
    if values is None:
        return key
    return values[0 if language == 'es' else 1].format(**kwargs)
